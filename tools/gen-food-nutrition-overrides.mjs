// Writes empty overrides for the duplicate TFC food definitions that
// farmersdelighttfc, Survivor's Delight, and tfc_cuisine ship for items that
// tfgm/nutrition.js already defines.
//
// TFC uses the first food definition whose ingredient matches, iterating the
// definition map in hash order, so when two mods define the same item under
// different ids the winner depends on hash order. Pointing the duplicates at the
// empty tfgm:empty tag leaves one definition per item. Same approach as
// aqua_fishes.json and slices_and_servings.json.
//
// Usage:
//   node tools/gen-food-nutrition-overrides.mjs --jars <dir of mod jars> \
//     --nutrition kubejs/server_scripts/tfgm/nutrition.js --out kubejs/data
//
// The jars dir must hold farmersdelighttfc*.jar, survivorsdelight*.jar and
// tfc_cuisine*.jar. Definitions are read with `unzip -p`.

import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { execSync } from "node:child_process";

function arg(name, def) {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : def;
}
const JARS = arg("jars", "/tmp/tfgmjars");
const NUTRITION = arg("nutrition", "kubejs/server_scripts/tfgm/nutrition.js");
const OUT = arg("out", "kubejs/data");

// Farmer's Delight feast block items are placed, not eaten, and have no food
// properties, so nutrition.js cannot register them. Their bridge mod keeps the
// single definition and nutrition.js skips them (FD_FEAST_BLOCKS there).
const FEAST_BLOCKS = new Set([
  "honey_glazed_ham_block",
  "rice_roll_medley_block",
  "roast_chicken_block",
  "shepherds_pie_block",
  "stuffed_pumpkin_block",
  "gleaming_salad_block",
]);
// Whole pies and cakes that nutrition.js now sets directly.
const ADDED = ["apple_pie", "chocolate_pie", "sweet_berry_cheesecake"];

const jarFor = (prefix) => {
  const hit = readdirSync(JARS).find((f) => f.startsWith(prefix) && f.endsWith(".jar"));
  if (!hit) throw new Error(`no jar starting with ${prefix} in ${JARS}`);
  return join(JARS, hit);
};
const entries = (jar) =>
  execSync(`unzip -Z1 ${jar} 'data/*/tfc/food_items/*.json' 'data/*/tfc/food_items/**/*.json'`, {
    encoding: "utf8",
  })
    .trim()
    .split("\n")
    .filter(Boolean);
const read = (jar, path) => execSync(`unzip -p ${jar} '${path}'`, { encoding: "utf8" });

const NUTS = ["grain", "fruit", "vegetables", "protein", "dairy"];
function defsOf(jar, itemNs) {
  const out = [];
  for (const file of [...new Set(entries(jar))]) {
    let j;
    try {
      j = JSON.parse(read(jar, file));
    } catch {
      continue;
    }
    if (!j.ingredient || !j.ingredient.item) continue;
    if (!j.ingredient.item.startsWith(itemNs + ":")) continue;
    out.push({
      file,
      item: j.ingredient.item,
      path: j.ingredient.item.split(":")[1],
      type: j.type || "static",
      real: j.type === "dynamic" || NUTS.some((k) => (j[k] || 0) > 0),
    });
  }
  return out;
}

const src = readFileSync(NUTRITION, "utf8");
function forkPaths(ns) {
  const s = new Set();
  const re = new RegExp(`foods\\(\\s*"${ns}"\\s*,\\s*"([^"]+)"`, "g");
  let m;
  while ((m = re.exec(src))) m[1].trim().split(/\s+/).forEach((p) => s.add(p));
  return s;
}
const forkFD = forkPaths("farmersdelight");
ADDED.forEach((p) => forkFD.add(p));
const priKeys = new Set();
{
  const re = /\[\s*"farmersdelight:([^"]+)"\s*,\s*"survivorsdelight:[^"]+"\s*\]/g;
  let m;
  while ((m = re.exec(src))) priKeys.add(m[1]);
}

const fdtfc = defsOf(jarFor("farmersdelighttfc"), "farmersdelight");
const sd = defsOf(jarFor("survivorsdelight"), "farmersdelight");
const tc = defsOf(jarFor("tfc_cuisine"), "cuisinedelight");
const fdtfcReal = new Set(fdtfc.filter((d) => d.real).map((d) => d.path));

const disable = [];
for (const d of fdtfc) {
  if (forkFD.has(d.path)) disable.push(d);
  // feast blocks and items nutrition.js does not cover: leave farmersdelighttfc's definition
}
for (const d of sd) {
  if (forkFD.has(d.path)) {
    if (!priKeys.has(d.path)) disable.push(d); // else nutrition.js replaces SD under the same id at runtime
  } else if (FEAST_BLOCKS.has(d.path) && fdtfcReal.has(d.path)) {
    disable.push(d); // farmersdelighttfc owns the block; drop SD's duplicate
  }
}
for (const d of tc) disable.push(d);

const toWrite = [];
for (const d of disable) {
  const body = {
    __comment__:
      "Disabled via an empty tag; nutrition for this item is set in tfgm/nutrition.js. Generated by tools/gen-food-nutrition-overrides.mjs.",
    ingredient: { tag: "tfgm:empty" },
    hunger: 1,
    saturation: 0,
    decay_modifier: 1,
  };
  if (d.type === "dynamic") body.type = "dynamic";
  toWrite.push({ path: join(OUT, d.file.replace(/^data\//, "")), body });
}

for (const w of toWrite) {
  mkdirSync(dirname(w.path), { recursive: true });
  writeFileSync(w.path, JSON.stringify(w.body, null, 2) + "\n");
}

const by = (p) => toWrite.filter((w) => w.path.includes(p)).length;
console.log(`wrote ${toWrite.length} overrides:`);
console.log(`  farmersdelighttfc: ${by("/food_items/farmersdelight/")}`);
console.log(`  survivorsdelight: ${by("/survivorsdelight/")}`);
console.log(`  tfc_cuisine: ${by("/tfc_cuisine/")}`);
